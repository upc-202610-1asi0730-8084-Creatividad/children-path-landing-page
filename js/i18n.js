class I18nEngine {
  constructor() {
    // Default language is English as requested ("por defecto tiene que estar este idioma")
    this.currentLang = localStorage.getItem("childrenpath_lang") || "en";
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindSelector();
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem("childrenpath_lang", lang);
      this.applyLanguage(lang);
    }
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    const langData = translations[lang];

    // Update text elements
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.getAttribute("data-i18n");
      if (langData[key] !== undefined) {
        // Handle line breaks in strings
        if (langData[key].includes("\n")) {
          element.innerText = langData[key];
        } else {
          element.textContent = langData[key];
        }
      }
    });

    // Update placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const key = element.getAttribute("data-i18n-placeholder");
      if (langData[key] !== undefined) {
        element.setAttribute("placeholder", langData[key]);
      }
    });

    // Update selector value if present
    const langSwitchers = document.querySelectorAll(".lang-select");
    langSwitchers.forEach((select) => {
      select.value = lang;
    });

    // Fire custom event
    document.dispatchEvent(new CustomEvent("languageChange", { detail: { lang } }));
  }

  bindSelector() {
    document.addEventListener("change", (e) => {
      if (e.target && e.target.classList.contains("lang-select")) {
        this.setLanguage(e.target.value);
      }
    });
  }
}

